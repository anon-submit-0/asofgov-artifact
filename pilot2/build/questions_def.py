def Q(qid, domain, zh, alias, T, as_of=None, scope=None, gold=None, **kw):
    q = {"qid": qid, "domain": domain, "question_zh": zh, "as_of": as_of,
         "declared_at": T, "metric_alias": alias, "scope": scope or {},
         "pinned_version": None, "cross_window": None, "anchor_override": None,
         "window_request": None, "requested_granularity": None,
         "requested_time_gran": None, "presentation": "aggregate",
         "ctx_role": "external_analyst", "periods": None}
    q.update(kw)
    q["_gold"] = gold
    return q

def G(kind, sql=None, reason=None, subtype=None, rewrite=None, windows=None,
      notes="", metric=None, expect_close=None, value_kind="scalar"):
    return {"expected_kind": kind, "gold_sql": sql, "refusal_reason": reason,
            "refusal_subtype": subtype, "rewrite": rewrite, "windows": windows,
            "notes": notes, "metric": metric, "expect_close": expect_close,
            "value_kind": value_kind}

def W(lo, hi, kind="range"):
    return {"kind": kind, "lo": lo, "hi_excl": hi}


